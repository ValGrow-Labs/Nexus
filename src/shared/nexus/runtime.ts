// The agent runtime contract (types only). Nexus reaches every agent engine
// through this interface; nothing in the data model, the job system, the UI or
// a workflow depends on which engine sits behind it. No implementation exists
// in B2a: adapters arrive in B2b (the default engine adapter wraps the Claude
// CLI, as the neutral runtime kind `cli-agent`; a scripted adapter replays
// fixtures for tests). Engine-specific names may appear in these comments only,
// never in a type or a value.

declare const runtimeKindBrand: unique symbol;
/** An opaque adapter id such as `scripted` (lowercase, `^[a-z][a-z0-9-]{0,31}$`). Branded: not a list of vendors. */
export type RuntimeKind = string & { readonly [runtimeKindBrand]: 'RuntimeKind' };

export type RuntimeHealth =
  | { ok: true; version: string }
  | { ok: false; reason: 'not_installed' | 'not_authenticated' | 'version_unsupported' | 'error'; detail: string };

export interface AgentRuntime {
  readonly kind: RuntimeKind;
  /**
   * `label`: the engine's display name, shown on the setup row only (D-B9). `egressHosts`: the destinations the agent
   * process needs, granted once in the setup sheet (D-B2); main never takes them from the renderer.
   */
  describe(): Promise<{ version: string; supportsHttpMcp: boolean; supportsResume: boolean; models: string[]; label: string;
    egressHosts: { host: string; port: number }[] }>;
  health(): Promise<RuntimeHealth>;
  /** Starts one turn. The iterable ends after exactly one of run.completed, run.failed or run.cancelled. */
  start(req: RunRequest, signal: AbortSignal): AsyncIterable<RuntimeEvent>;
  cancel(runRef: string, graceMs: number): Promise<void>;
  respondApproval?(runRef: string, approvalRef: string, decision: 'once' | 'deny'): Promise<void>;
}

export interface RunRequest {
  jobId: string; attempt: number; sessionId: string; idempotencyKey: string;
  resumeRef?: string;                                   // the runtime's own conversation id, when it supports resume
  domainId: string;
  skills: { id: string; version: string; dir: string; sha256: string }[];
  context: { hash: string; file: string };              // resolved context written by main into the job config dir
  message: string;
  worktree: { hostPath: string; editable: string[] };   // file tools confined here
  container: { id: string };                            // the turn's sandbox
  mcp: { url: string };                                 // the token travels in memory only: never in argv, a file, the model context or a log
  model: { provider: string; model: string };           // opaque ids chosen in settings; no vendor is assumed
  limits: { wallClockMs: number; maxTurns: number; maxCostUsd?: number };
  /** Local-model runtime only: the loopback endpoint main read from the user's settings. Must be a loopback address and equal the consented host. */
  endpoint?: { host: string; port: number };
  credential: { ref: string };                          // a reference, never the secret; B2b: 'runtime-owned' (the engine keeps its own login)
  configDir: string;                                    // per-job, generated by main, deleted with the job's work dir
}

export type RuntimeEvent =
  | { t: 'run.started'; runRef: string; at: number }
  | { t: 'message.delta'; text: string }               // display only; never evidence
  | { t: 'tool.started'; callId: string; tool: string; argsSummary: string }
  | { t: 'tool.completed'; callId: string; ok: boolean; resultBytes: number }
  | { t: 'approval.requested'; approvalRef: string; summary: string }
  | ({ t: 'usage' } & AgentUsage)                       // cumulative for the turn: monotonic, never a delta
  | { t: 'run.completed'; at: number; stopReason: string }
  | { t: 'run.failed'; at: number; code: 'runtime_error' | 'auth' | 'limit' | 'protocol'; message: string }
  | { t: 'run.cancelled'; at: number };

/**
 * What one turn used, as the runtime reported it. Cumulative and monotonic within a turn. Capped tokens are input +
 * output + cache creation; cache reads are reported but not capped (F10). `costUsdCents` is null when the runtime
 * reported no cost: the turn is then charged at its cap, and `estimated` is true.
 */
export interface AgentUsage {
  inputTokens: number;
  outputTokens: number;
  cacheCreationTokens: number;
  cacheReadTokens: number;
  costUsdCents: number | null;
  toolCalls: number;
  estimated: boolean;
}
